/*
  Responsive, content-hashed images generated by `npm run images`.
  Components keep using the original paths (e.g. "/renet-hero.png");
  responsiveImage() swaps them for WebP + srcset at render time.
*/
const files = import.meta.glob("../assets/optimized/*.webp", { eager: true, query: "?url", import: "default" });

const sets = {};
for (const [file, url] of Object.entries(files)) {
  const [, name, width] = file.match(/\/([^/]+)-(\d+)\.webp$/);
  (sets[name] ??= []).push({ url, width: Number(width) });
}
for (const list of Object.values(sets)) list.sort((a, b) => a.width - b.width);

const nameOf = (path) => path.replace(/^.*\//, "").replace(/\.(png|jpe?g|webp)$/i, "");

/*
  Props for an <img>: { src, srcSet, sizes }.
  `sizes` describes the rendered width so the browser downloads the smallest
  file that is still sharp (e.g. "100vw", "(max-width: 768px) 100vw, 33vw").
*/
export function responsiveImage(path, sizes = "100vw") {
  const list = sets[nameOf(path)];
  if (!list) return { src: path };
  const fallback = list.find((item) => item.width >= 960) ?? list.at(-1);
  return {
    src: fallback.url,
    srcSet: list.map((item) => `${item.url} ${item.width}w`).join(", "),
    sizes,
  };
}

// Single URL at roughly the requested width (for CSS backgrounds).
export function imageUrl(path, width = 1280) {
  const list = sets[nameOf(path)];
  if (!list) return path;
  return (list.find((item) => item.width >= width) ?? list.at(-1)).url;
}
